/**
 * 영수증 판독 프롬프트.
 *
 * 회사 PC 폴러가 Agent SDK로 이미지를 `Read` 해 읽는다(어시스턴트와 같은 경로).
 * **프롬프트는 서버가 만든다** — 고칠 때 회사 PC를 만지지 않기 위해서다.
 *
 * 실측(2026-08-19): 실제 종이 영수증 사진으로 접수번호·일시·등기 3건의
 * 등기번호·요금·우편번호·수취인까지 **15/15 일치**. 카드 정보는 담지 않았다.
 */
export function buildExtractPrompt(fileName: string): string {
  return `이 폴더의 \`${fileName}\` 를 Read 로 열어라. 우체국 등기 영수증이다.

읽은 값을 아래 JSON 한 덩어리로만 답하라. 설명·코드펜스 없이 JSON만.

{
  "is_receipt": true,
  "receipt_no": "접수번호",
  "accepted_at": "접수일자 YYYY-MM-DD HH:mm",
  "total_fee": 합계금액숫자,
  "approved_amount": 카드승인금액숫자,
  "item_count": 합계통수,
  "items": [
    {"tracking_no":"등기번호","fee":요금숫자,"postal_code":"우편번호","recipient_org":"수취인 소속","recipient_name":"수취인 이름"}
  ]
}

규칙:
- **카드번호·승인번호·가맹점번호·카드사명은 절대 담지 마라.** 업무에 쓸 일이 없고, 담으면 안 되는 정보다.
- "approved_amount" 는 **승인금액**(결제된 돈)이다. 개별 요금 합과 다를 수 있는데 그게 정상이다 — 보이는 대로 적어라. 없으면 null.
- 수취인은 "우석대 강정화"처럼 **소속과 이름**이 붙어 있다. 마지막 낱말이 이름, 앞이 소속이다. 소속에 "대학원"이 적혀 있으면 그대로 살려라 — 담당자를 가르는 기준이다.
- 요금·금액은 쉼표를 뺀 숫자로.
- 등기번호는 보이는 형태(하이픈 포함) 그대로.
- **안 보이는 값은 지어내지 말고 null.** 흐릿해서 못 읽으면 그 항목만 null로 둔다.
- 우체국 등기 영수증이 아니면 {"is_receipt": false} 만 답하라.`;
}
