/**
 * `인증번호` **바로 뒤**의 대괄호 4~8자리만 코드다. 조사(는/은)와 공백은 허용한다.
 *
 * Moa 실문자: `[Web발신][내부관리자] 본인확인 인증번호는 [130753] 입니다.`
 */
const CODE_AFTER_HINT = /인증\s*번호[는은]?\s*\[([0-9]{4,8})\]/;

/**
 * 인증문자인가, 코드는 무엇인가 — 둘을 한 함수가 답한다. `null` 이면 인증문자가 아니다.
 *
 * 본문 아무 데나 있는 대괄호 숫자를 집으면 두 방향으로 틀린다(리뷰에서 잡음,
 * 2026-09-11): 앞에 놓인 `[2026]` 을 코드로 저장하고(→ 틀린 코드 제출 → 캡차 잠금),
 * `[광고] 인증번호 이벤트 [9999]` 같은 스팸도 코드로 앉는다. 키워드에 **붙은** 것만
 * 본다.
 *
 * 대괄호 없는 느슨한 규칙은 두지 않는다 — 전화번호·금액을 코드로 저장한다. 포맷이
 * 바뀌면 우편함이 비어 **시끄럽게** 실패하는 편이 낫다.
 */
export function extractSmsCode(body: string): string | null {
  return CODE_AFTER_HINT.exec(body)?.[1] ?? null;
}
